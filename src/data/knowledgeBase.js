/**
 * Normalizes a query string for high accuracy matching.
 */
function cleanString(str) {
  return str
    .toLowerCase()
    .replace(/[^\w\s+#.]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Stopwords to ignore in general scoring to prevent false positives.
 */
const STOP_WORDS = new Set([
  'a', 'an', 'the', 'is', 'are', 'was', 'were', 'be', 'been', 'being',
  'in', 'on', 'at', 'to', 'for', 'of', 'with', 'by', 'about', 'like',
  'through', 'over', 'before', 'between', 'under', 'along',
  'i', 'me', 'my', 'myself', 'we', 'our', 'you', 'your', 'he', 'him',
  'his', 'she', 'her', 'it', 'its', 'they', 'them', 'their',
  'what', 'which', 'who', 'whom', 'this', 'that', 'these', 'those',
  'am', 'have', 'has', 'had', 'do', 'does', 'did', 'can', 'could',
  'should', 'would', 'tell', 'show', 'give', 'know', 'does'
]);

/**
 * High-speed local answer matcher.
 * Matches keywords and phrases using a multi-tiered precision algorithm.
 * 
 * @param {string} rawQuery - The user question
 * @returns {{ answer: string, confidence: number, id: string } | null}
 */
export function findAnswer(rawQuery) {
  if (!rawQuery || typeof rawQuery !== 'string') return null;

  const query = cleanString(rawQuery);
  if (!query) return null;

  const queryTokens = query.split(' ').filter(w => w.length > 0);
  const meaningfulQueryTokens = queryTokens.filter(w => !STOP_WORDS.has(w));

  let bestMatch = null;
  let highestScore = 0;

  // Specific high-priority quick matches
  const directMappings = [
    { test: /^(who is satyam|who satyam|satyam bio|about satyam|satyam kumar\??)$/i, id: 'who-is-satyam' },
    { test: /^(satyam)$/i, id: 'satyam-single-keyword' },
    { test: /^(c\+\+|cpp|c plus plus)$/i, id: 'skill-cpp' },
    { test: /^(programming|coding|languages)$/i, id: 'skill-programming' },
    { test: /^(skills|tech stack|expertise)$/i, id: 'all-skills' },
    { test: /^(projects|portfolio|built)$/i, id: 'all-projects' },
    { test: /^(ai|artificial intelligence|ml|machine learning)$/i, id: 'skill-ai' },
    { test: /^(web development|web dev|frontend|full stack)$/i, id: 'skill-web-development' },
    { test: /^(savify|startup)$/i, id: 'what-is-savify' },
    { test: /^(experience|work|jobs)$/i, id: 'experience-overview' },
    { test: /^(education|college|lpu|degree)$/i, id: 'education-overview' },
    { test: /^(github|git|repos|repositories)$/i, id: 'github-profile' },
    { test: /^(contact|email|reach|message)$/i, id: 'contact-details' },
    { test: /^(certifications|certificates)$/i, id: 'all-certifications' },
    { test: /^(hackathons|competitions)$/i, id: 'hackathons-list' },
    { test: /^(leetcode|cp|competitive programming)$/i, id: 'competitive-programming' },
    { test: /^(cv|resume|download cv|view cv|download resume|view resume|curriculum vitae)$/i, id: 'resume-cv' },
    { test: /^(phone|mobile|phone number|mobile number|call)$/i, id: 'phone-mobile' }
  ];

  for (const mapping of directMappings) {
    if (mapping.test.test(query)) {
      const entry = knowledgeBase.find(e => e.id === mapping.id);
      if (entry) {
        return { answer: entry.answer, confidence: 100, id: entry.id };
      }
    }
  }

  for (const entry of knowledgeBase) {
    let score = 0;

    for (const keyword of entry.keywords) {
      const cleanKw = cleanString(keyword);
      if (!cleanKw) continue;

      // 1. Exact query match with keyword
      if (query === cleanKw) {
        score += 80;
        break;
      }

      // 2. Exact keyword phrase found in query
      if (query.includes(cleanKw)) {
        const wordCount = cleanKw.split(' ').length;
        score += 25 * wordCount;
      }

      // 3. Exact query found in keyword
      if (cleanKw.includes(query) && query.length >= 3) {
        score += 20;
      }

      // 4. Token overlap scoring
      const kwTokens = cleanKw.split(' ').filter(w => !STOP_WORDS.has(w));
      let matchCount = 0;

      for (const qTok of meaningfulQueryTokens) {
        for (const kTok of kwTokens) {
          if (qTok === kTok) {
            matchCount++;
            score += 10;
          } else if (qTok.length >= 4 && kTok.length >= 4 && (qTok.includes(kTok) || kTok.includes(qTok))) {
            score += 4;
          }
        }
      }

      if (kwTokens.length > 0 && matchCount === kwTokens.length) {
        score += 15; // Full keyword coverage bonus
      }
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = entry;
    }
  }

  // Acceptance threshold
  if (bestMatch && highestScore >= 12) {
    return {
      answer: bestMatch.answer,
      confidence: highestScore,
      id: bestMatch.id
    };
  }

  return null;
}

